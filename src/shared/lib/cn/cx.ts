import { type ClassValue, clsx } from 'clsx';

/**
 * # Склейка классов БЕЗ разрешения конфликтов
 * Голый `clsx` (~0.3 КБ) — для клиентских островов. `cn` тянет за собой
 * `tailwind-merge` (~10 КБ gzip), и в серверных компонентах это бесплатно, а в
 * клиентском бандле — нет. Правило: в `'use client'`-модулях классы
 * склеиваются через `cx`, и наборы пишутся без конфликтующих утилит (одно
 * свойство — один класс на состояние).
 *
 * @param inputs - произвольный набор классов/условий
 * @returns строка классов
 */
export const cx = (...inputs: ClassValue[]): string => clsx(inputs);
